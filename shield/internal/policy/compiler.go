package policy

import (
	"bytes"
	"fmt"
	"text/template"

	"gopkg.in/yaml.v3"
)

// CompileYAMLBytesToRego parses YAML policy bytes and compiles them to a native Rego module.
func CompileYAMLBytesToRego(b []byte) (string, error) {
	var f File
	if err := yaml.Unmarshal(b, &f); err != nil {
		return "", fmt.Errorf("compile yaml: %w", err)
	}
	if f.Version != "1" {
		return "", fmt.Errorf("compile yaml: unsupported version %q", f.Version)
	}
	if f.DefaultAction == "" {
		f.DefaultAction = Deny
	}
	return CompileYAMLToRego(&f)
}

type compilerData struct {
	Version             string
	DefaultAction       string
	DryRun              bool
	GlobalDenyPatterns  []string
	BlockSecretsInArgs  bool
	GlobalEgressBlockPN bool
	GlobalDenyDomains   []string
	GlobalAllowDomains  []string
	Agents              []compilerAgent
}

type compilerAgent struct {
	ID                 string
	MaxStepsPerSession int
	RateLimitPerMinute int
	HasDryRun          bool
	DryRun             bool
	Tools              []compilerTool
	HasEgress          bool
	AllowDomains       []string
	DenyDomains        []string
	BlockPrivateNet    bool
}

type compilerTool struct {
	Name            string
	RequireScope    string
	RequireApproval bool
	Deny            bool
	DenyArgPatterns []string
}

// CompileYAMLToRego compiles a File structure to an Open Policy Agent Rego v1 document.
func CompileYAMLToRego(f *File) (string, error) {
	d := compilerData{
		Version:             f.Version,
		DefaultAction:       string(f.DefaultAction),
		DryRun:              f.DryRun,
		GlobalDenyPatterns:  f.Global.DenyArgPatterns,
		BlockSecretsInArgs:  f.Global.BlockSecretsInArguments,
		GlobalEgressBlockPN: boolOr(f.Global.Egress.BlockPrivateNetworks, true),
		GlobalDenyDomains:   f.Global.Egress.DenyDomains,
		GlobalAllowDomains:  f.Global.Egress.AllowDomains,
	}

	for _, a := range f.Agents {
		ca := compilerAgent{
			ID:                 a.ID,
			MaxStepsPerSession: a.MaxStepsPerSession,
			RateLimitPerMinute: a.RateLimitPerMinute,
		}
		if a.DryRun != nil {
			ca.HasDryRun = true
			ca.DryRun = *a.DryRun
		}
		for _, t := range a.Tools {
			ca.Tools = append(ca.Tools, compilerTool{
				Name:            t.Name,
				RequireScope:    t.RequireScope,
				RequireApproval: t.RequireApproval,
				Deny:            t.Deny,
				DenyArgPatterns: t.DenyArgPatterns,
			})
		}
		if a.Egress != nil {
			ca.HasEgress = true
			ca.AllowDomains = a.Egress.AllowDomains
			ca.DenyDomains = a.Egress.DenyDomains
			ca.BlockPrivateNet = boolOr(a.Egress.BlockPrivateNetworks, true)
		}
		d.Agents = append(d.Agents, ca)
	}

	tmpl, err := template.New("rego").Funcs(template.FuncMap{
		"quote": func(s string) string {
			return fmt.Sprintf("%q", s)
		},
	}).Parse(regoTemplate)
	if err != nil {
		return "", fmt.Errorf("template parse error: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, d); err != nil {
		return "", fmt.Errorf("template execute error: %w", err)
	}

	return buf.String(), nil
}

const regoTemplate = `package mcpguard.policy

import rego.v1

# Auto-generated by Sentinel mcpguard policy compiler. DO NOT EDIT DIRECTLY.
# Policy Version: {{ .Version }}

default decision := {"action": "deny", "rule": "tool_not_allowed", "reason": "blocked by default policy"}

# Main entrypoint
decision := final_decision

final_decision := out if {
	d := raw_decision
	is_dry_run
	d.action in ["deny", "pending"]
	out := object.union(d, {
		"action": "allow",
		"dry_run": true,
		"original_action": d.action,
	})
} else := raw_decision

is_dry_run if {
	object.get(agent_profile, "dry_run", null) == true
} else if {
	dry_run_global == true
	object.get(agent_profile, "dry_run", null) != false
}

dry_run_global := {{ .DryRun }}
default_action := {{ quote .DefaultAction }}

raw_decision := d if {
	some d in [check_max_steps]
} else := d if {
	some d in [check_rate_limit]
} else := d if {
	some d in [check_tool]
} else := d if {
	some d in [check_deny_patterns]
} else := d if {
	some d in [check_secrets]
} else := d if {
	some d in [check_egress]
} else := d if {
	some d in [check_approval]
} else := {"action": "allow", "rule": "allow", "reason": "allowed"}

# Global configuration
global_deny_patterns := [
{{ range .GlobalDenyPatterns }}	{{ quote . }},
{{ end }}]

block_secrets_in_args := {{ .BlockSecretsInArgs }}

global_egress := {
	"block_private_networks": {{ .GlobalEgressBlockPN }},
	"deny_domains": [
{{ range .GlobalDenyDomains }}		{{ quote . }},
{{ end }}	],
	"allow_domains": [
{{ range .GlobalAllowDomains }}		{{ quote . }},
{{ end }}	],
}

# Agent Profiles
agents := {
{{ range .Agents }}	{{ quote .ID }}: {
		"max_steps_per_session": {{ .MaxStepsPerSession }},
		"rate_limit_per_minute": {{ .RateLimitPerMinute }},
{{ if .HasDryRun }}		"dry_run": {{ .DryRun }},
{{ end }}		"tools": [
{{ range .Tools }}			{
				"name": {{ quote .Name }},
				"require_scope": {{ quote .RequireScope }},
				"require_approval": {{ .RequireApproval }},
				"deny": {{ .Deny }},
				"deny_arg_patterns": [
{{ range .DenyArgPatterns }}					{{ quote . }},
{{ end }}				],
			},
{{ end }}		],
{{ if .HasEgress }}		"egress": {
			"allow_domains": [
{{ range .AllowDomains }}				{{ quote . }},
{{ end }}			],
			"deny_domains": [
{{ range .DenyDomains }}				{{ quote . }},
{{ end }}			],
			"block_private_networks": {{ .BlockPrivateNet }},
		},
{{ end }}	},
{{ end }}}

agent_profile := p if {
	p := object.get(agents, input.principal.agent_id, null)
	p != null
} else := p if {
	p := object.get(agents, "*", null)
	p != null
} else := null

# 1. Runaway breaker: max steps per session
check_max_steps := {"action": "deny", "rule": "max_steps_per_session", "reason": sprintf("session exceeded %d tool calls; a human must start a new session", [agent_profile.max_steps_per_session])} if {
	agent_profile != null
	agent_profile.max_steps_per_session > 0
	input.counters.steps > agent_profile.max_steps_per_session
}

# 2. Rate limit
check_rate_limit := {"action": "deny", "rule": "rate_limit", "reason": "rate limit exceeded for this agent session"} if {
	agent_profile != null
	agent_profile.rate_limit_per_minute > 0
	input.counters.rate > agent_profile.rate_limit_per_minute
}

# 3. Tool matching
matched_deny_tool := t if {
	agent_profile != null
	tools := object.get(agent_profile, "tools", [])
	some t in tools
	t.deny == true
	glob.match(t.name, [], input.tool)
}

matched_allow_tool := t if {
	agent_profile != null
	not matched_deny_tool
	tools := object.get(agent_profile, "tools", [])
	some t in tools
	not t.deny
	glob.match(t.name, [], input.tool)
}

has_scope(required) if {
	some s in input.principal.scopes
	s == required
}

check_tool := {"action": "deny", "rule": "tool_denied", "reason": sprintf("tool %q is explicitly denied", [input.tool])} if {
	matched_deny_tool != null
} else := {"action": "deny", "rule": "tool_not_allowed", "reason": sprintf("tool %q is not on this agent's allowlist", [input.tool])} if {
	agent_profile == null
	default_action != "allow"
} else := {"action": "deny", "rule": "tool_not_allowed", "reason": sprintf("tool %q is not on this agent's allowlist", [input.tool])} if {
	agent_profile != null
	not matched_deny_tool
	not matched_allow_tool
	default_action != "allow"
} else := {"action": "deny", "rule": "missing_scope", "reason": sprintf("agent token lacks scope %q", [matched_allow_tool.require_scope])} if {
	matched_allow_tool != null
	matched_allow_tool.require_scope != ""
	not has_scope(matched_allow_tool.require_scope)
}

# 4. Deny Argument Patterns
arguments := object.get(input, "arguments", {})
arg_strings := [val | some path, val in walk(arguments); is_string(val)]

active_deny_patterns := array.concat(
	global_deny_patterns,
	object.get(matched_allow_tool, "deny_arg_patterns", [])
)

matching_deny_pattern := p if {
	some p in active_deny_patterns
	some s in arg_strings
	regex.match(p, s)
}

check_deny_patterns := {"action": "deny", "rule": "deny_arg_pattern", "reason": concat("", ["arguments match a blocked pattern: ", matching_deny_pattern])} if {
	matching_deny_pattern != null
}

# 5. Secrets Detection
secret_patterns := {
	"private_key": "-----BEGIN [A-Z ]*PRIVATE KEY-----",
	"jwt": "\\beyJ[A-Za-z0-9_-]{8,}\\.[A-Za-z0-9_-]{8,}\\.[A-Za-z0-9_-]{8,}\\b",
	"aws_access_key": "\\b(?:AKIA|ASIA)[0-9A-Z]{16}\\b",
	"github_token": "\\b(?:gh[pousr]_[A-Za-z0-9]{36,255}|github_pat_[A-Za-z0-9_]{22,255})\\b",
	"anthropic_key": "\\bsk-ant-[A-Za-z0-9_-]{20,}\\b",
	"openai_key": "\\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}\\b",
	"slack_token": "\\bxox[abprs]-[A-Za-z0-9-]{10,}\\b",
}

detected_secret_kind := k if {
	block_secrets_in_args == true
	some k, pat in secret_patterns
	some s in arg_strings
	regex.match(pat, s)
}

check_secrets := {"action": "deny", "rule": "secret_in_arguments", "reason": sprintf("arguments contain credentials (%s); possible exfiltration", [detected_secret_kind])} if {
	detected_secret_kind != null
}

# 6. Egress Validation
merged_allow_domains := d if {
	agent_profile != null
	eg := object.get(agent_profile, "egress", {})
	al := object.get(eg, "allow_domains", [])
	count(al) > 0
	d := al
} else := d if {
	d := object.get(global_egress, "allow_domains", [])
}

merged_deny_domains := array.concat(
	object.get(global_egress, "deny_domains", []),
	object.get(object.get(agent_profile, "egress", {}), "deny_domains", [])
)

block_private := b if {
	agent_profile != null
	eg := object.get(agent_profile, "egress", {})
	bp := object.get(eg, "block_private_networks", null)
	bp != null
	b := bp
} else := b if {
	b := object.get(global_egress, "block_private_networks", true)
}

url_pattern := "(?i)\\b(?:https?|ftp|gopher|file)://[^\\s'\"<>()]+"
found_urls := [u | some s in arg_strings; some u in regex.find_all_string_submatch_n(url_pattern, s, -1)[_]]

parse_url(u) := {"scheme": scheme, "host": host} if {
	m := regex.find_all_string_submatch_n("(?i)^([a-z]+)://([^/?#:]+)", u, 1)
	count(m) > 0
	scheme := lower(m[0][1])
	host := lower(m[0][2])
}

is_ipv4(h) if {
	regex.match("^(\\d{1,3}\\.){3}\\d{1,3}$", h)
}

is_internal_host(h) if {
	h in ["localhost", "metadata.google.internal", "metadata", "instance-data"]
} else if {
	endswith(h, ".internal")
} else if {
	endswith(h, ".local")
} else if {
	endswith(h, ".localhost")
} else if {
	is_ipv4(h)
	net.cidr_contains("127.0.0.0/8", h)
} else if {
	is_ipv4(h)
	net.cidr_contains("10.0.0.0/8", h)
} else if {
	is_ipv4(h)
	net.cidr_contains("172.16.0.0/12", h)
} else if {
	is_ipv4(h)
	net.cidr_contains("192.168.0.0/16", h)
} else if {
	is_ipv4(h)
	net.cidr_contains("169.254.0.0/16", h)
}

domain_matches(host, pattern) if {
	startswith(pattern, "*.")
	suffix := substring(pattern, 1, -1)
	endswith(host, suffix)
} else if {
	host == pattern
}

domain_in_list(host, list) if {
	some p in list
	domain_matches(host, lower(p))
}

egress_violation := {"rule": "egress_scheme", "reason": "file:// URLs are not allowed"} if {
	some u in found_urls
	startswith(lower(u), "file://")
} else := {"rule": "egress_scheme", "reason": sprintf("URL scheme %s is not allowed", [parse_url(u).scheme])} if {
	some u in found_urls
	p := parse_url(u)
	not p.scheme in ["http", "https"]
} else := {"rule": "egress_private_network", "reason": sprintf("blocked request to internal address %s", [parse_url(u).host])} if {
	block_private
	some u in found_urls
	h := parse_url(u).host
	is_internal_host(h)
} else := {"rule": "egress_deny_domain", "reason": sprintf("domain %s is denied", [parse_url(u).host])} if {
	some u in found_urls
	h := parse_url(u).host
	domain_in_list(h, merged_deny_domains)
} else := {"rule": "egress_not_allowlisted", "reason": sprintf("domain %s is not on the egress allowlist", [parse_url(u).host])} if {
	count(merged_allow_domains) > 0
	some u in found_urls
	h := parse_url(u).host
	not domain_in_list(h, merged_allow_domains)
} else := {"rule": "egress_private_network", "reason": sprintf("blocked reference to internal address %s", [ip])} if {
	block_private
	ipv4_pattern := "\\b(?:\\d{1,3}\\.){3}\\d{1,3}\\b"
	some s in arg_strings
	some m in regex.find_all_string_submatch_n(ipv4_pattern, s, -1)
	ip := m[0]
	is_internal_host(ip)
}

check_egress := {"action": "deny", "rule": egress_violation.rule, "reason": egress_violation.reason} if {
	egress_violation != null
}

# 7. Require Approval
check_approval := {"action": "pending", "rule": "require_approval", "reason": "this call needs human approval; retry the identical call after approval"} if {
	matched_allow_tool != null
	matched_allow_tool.require_approval == true
}
`
